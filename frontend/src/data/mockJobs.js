/**
 * Filter and get matching jobs for a user based on their skills and sector.
 */
export function getMatchingJobs(userSkills = [], filters = {}) {
  const normUserSkills = (userSkills || []).map((s) => s.toLowerCase());

  return mockJobs
    .filter((job) => {
      if (job.status !== 'active') return false;
      if (filters.type && filters.type !== 'all' && job.job_type !== filters.type) return false;
      if (filters.location_type && filters.location_type !== 'all' && job.location_type !== filters.location_type) return false;
      if (filters.experience_level && filters.experience_level !== 'all' && job.experience_level !== filters.experience_level) return false;
      if (filters.sector && filters.sector !== 'all') {
        if (filters.sector === 'government' && !job.is_government) return false;
        if (filters.sector === 'private' && (job.is_government || job.location_type === 'remote')) return false;
        if (filters.sector === 'remote' && job.location_type !== 'remote') return false;
      }
      if (filters.remote_only && job.location_type !== 'remote') return false;
      if (filters.exclude_bangladesh && job.country === 'Bangladesh') return false;
      if (filters.government_only && !job.is_government) return false;
      if (filters.search) {
        const q = filters.search.toLowerCase();
        const searchable = `${job.title} ${job.company_name} ${job.description} ${(job.required_skills || []).join(' ')} ${job.department || ''} ${job.location || ''}`.toLowerCase();
        if (!searchable.includes(q)) return false;
      }
      return true;
    })
    .map((job) => {
      const allSkills = [...job.required_skills, ...(job.preferred_skills || [])];
      const matchedSkills = (userSkills || []).filter((s) =>
        allSkills.some((js) => js.toLowerCase() === s.toLowerCase())
      );
      const missedRequired = (job.required_skills || []).filter(
        (s) => !normUserSkills.includes(s.toLowerCase())
      );

      // Score calculation
      let matchScore = 45;
      if (allSkills.length > 0 && userSkills && userSkills.length > 0) {
        const skillRatio = matchedSkills.length / Math.min(allSkills.length, 6);
        matchScore = Math.min(96, Math.max(35, Math.round(skillRatio * 100)));
      } else if (job.is_government) {
        // Government entry level matches are broader
        matchScore = 70;
      }

      return {
        ...job,
        match_score: matchScore,
        matched_skills: matchedSkills,
        missing_skills: missedRequired,
      };
    })
    .sort((a, b) => b.match_score - a.match_score);
}

export function getRemoteJobs(userSkills = []) {
  return getMatchingJobs(userSkills, { remote_only: true, exclude_bangladesh: true });
}

export function getGovernmentJobs(userSkills = []) {
  return getMatchingJobs(userSkills, { government_only: true });
}

export function getJobById(id) {
  return mockJobs.find((j) => j.id === id) || null;
}

export function getCompanyById(id) {
  return mockCompanies.find((c) => c.id === id) || null;
}

export function getJobsByCompany(companyId) {
  return mockJobs.filter((j) => j.company_id === companyId && j.status === 'active');
}
